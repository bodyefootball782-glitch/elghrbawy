-- Automatic activity log entries for the main platform actions.
create or replace function public.log_activity_change() returns trigger language plpgsql security definer set search_path=public as $$
declare actor uuid; rowj jsonb; target text; display_name text;
begin
  actor := auth.uid();
  rowj := case when TG_OP='DELETE' then to_jsonb(old) else to_jsonb(new) end;
  target := coalesce(rowj->>'id','');
  display_name := coalesce(rowj->>'full_name',rowj->>'title',rowj->>'status','');
  insert into public.activity_logs(event_type,actor_id,target_id,details)
  values (TG_TABLE_NAME||':'||lower(TG_OP), actor, target, jsonb_build_object('table',TG_TABLE_NAME,'operation',TG_OP,'name',display_name));
  return case when TG_OP='DELETE' then old else new end;
end; $$;
drop trigger if exists profiles_activity_log on public.profiles; create trigger profiles_activity_log after insert or update or delete on public.profiles for each row execute procedure public.log_activity_change();
