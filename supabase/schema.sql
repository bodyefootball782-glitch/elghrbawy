create or replace function public.protect_student_profile() returns trigger language plpgsql security definer set search_path=public as $$
begin
  if auth.uid() = old.id and not public.is_admin() then
    new.role := old.role;
    new.xp := old.xp;
    new.id := old.id;
    new.phone := old.phone;
    new.login_email := old.login_email;
    new.account_type := old.account_type;
  end if;
  return new;
end; $$;
