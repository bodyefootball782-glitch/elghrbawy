create or replace function public.get_exam_questions(p_exam_id bigint)
returns table(id bigint,question text,options jsonb,sort_order integer)
language plpgsql security definer set search_path=public as $$
begin
 if not exists(select 1 from public.exams where public.exams.id=p_exam_id and is_published=true) and not public.is_admin() then raise exception 'Exam is not available'; end if;
 return query select q.id,q.question,q.options,q.sort_order from public.exam_questions q where q.exam_id=p_exam_id order by q.sort_order,q.id;
end; $$;
revoke all on function public.get_exam_questions(bigint) from public; grant execute on function public.get_exam_questions(bigint) to authenticated;

create or replace function public.submit_exam(p_exam_id bigint,p_answers jsonb)
returns bigint language plpgsql security definer set search_path=public as $$
declare qcount integer; score integer:=0; i integer; answer integer; rid bigint; total integer; pct numeric; rec record;
begin
 if auth.uid() is null then raise exception 'Not authenticated'; end if;
 if exists(select 1 from public.results where student_id=auth.uid() and exam_id=p_exam_id) then raise exception 'You have already submitted this exam'; end if;
 if not exists(select 1 from public.exams where id=p_exam_id and is_published=true) then raise exception 'Exam is not available'; end if;
 select count(*) into qcount from public.exam_questions where exam_id=p_exam_id;
 if qcount=0 then raise exception 'Exam has no questions'; end if;
 total:=qcount;
 i:=0;
 for rec in (select correct_index from public.exam_questions where exam_id=p_exam_id order by sort_order,id) loop
   answer:=nullif((p_answers->>i),'')::integer;
   if answer is not null and answer=rec.correct_index then score:=score+1; end if;
   i:=i+1;
 end loop;
 pct:=round((score::numeric/total::numeric)*100,2);
 insert into public.results(student_id,exam_id,score,total,percentage,answers) values(auth.uid(),p_exam_id,score,total,pct,p_answers) returning id into rid;
 update public.profiles set xp=xp+(score*10) where id=auth.uid();
 return rid;
end; $$;
revoke all on function public.submit_exam(bigint,jsonb) from public; grant execute on function public.submit_exam(bigint,jsonb) to authenticated;

